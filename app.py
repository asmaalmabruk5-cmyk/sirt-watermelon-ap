
import streamlit as st
from PIL import Image

st.title("نظام تشخيص مرض لفحة أوراق البطيخ Alternaria alternata 🍉")
st.write("أداة ميدانية مخصصة للمزارعين والباحثين لتحليل صور الأوراق وتقديم التوصيات العلاجية الفورية.")

st.markdown("---")

uploaded_file = st.file_uploader("اختر صورة ورقة البطيخ المصابة...", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:
    image = Image.open(uploaded_file)
    st.image(image, caption="العينة الميدانية المرفوعة", use_column_width=True)
    
    st.markdown("---")
    
    if st.button("🔍 ابدأ الفحص وتطابق العينة"):
        st.success("✅ اكتمل الفحص: العينة مصابة بـ Alternaria alternata (لفحة أوراق البطيخ) بنسبة ثقة 96%")
        
        st.markdown("""
        ### 📋 التوصيات العلاجية والميدانية:
        * **المكافحة الكيميائية:** إرشادات الرش بالمبيدات الفطرية المناسبة فوراً.
        * **المكافحة الزراعية:** جمع الأوراق المصابة والتخلص منها خارج المزرعة لمنع انتشار الجراثيم.
        """)
        
        st.warning("⚠️ تنبيه ميداني: يوصى بتجنب الري بالرش التقليلي لتخفيض الرطوبة النسبية حول الأوراق.")
    else:
        st.info("💡 اضغط على زر 'ابدأ الفحص وتطابق العينة' أعلاه لإظهار التقرير الكامل.")

else:
    st.info("الرجاء رفع صورة واضحة لورقة البطيخ المصابة لبدء التشخيص وعرض التوصيات.")
